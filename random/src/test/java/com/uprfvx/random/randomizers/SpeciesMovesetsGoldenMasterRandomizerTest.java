/**
 * Golden-master (characterization) test for species level-up learnsets and egg moves.
 * <p>
 * The rest of the species-moveset suite asserts <i>properties</i> - that a weight falls off, that a fallback
 * rung fires, that a floor holds. None of it asserts <i>output identity</i>, so a refactor that quietly
 * shifts the RNG call sequence passes every one of them while changing what every seed produces. This test
 * closes that gap: it freezes the exact learnset the randomizer writes for a fixed seed, so any drift shows
 * up as a precise diff. It documents what the code does today; it is not a claim that today's output is
 * "correct". When a behaviour change is intentional, re-bless the snapshot (see below).
 * <p>
 * <b>Coverage is by configuration, not by generation.</b> The four paths through
 * {@link SpeciesMovesetRandomizer#randomizeMovesLearnt()} are chosen by settings rather than by ROM, so each
 * game is frozen under all four:
 * <ul>
 *   <li>{@code SENSIBLE_TYPED} - Sensible Movesets on, Prefer Same Type: the composed path with type
 *       structure live (roles, power ceiling, STAB floor), plus Force Good Damaging to exercise the
 *       damaging-slot shuffle.</li>
 *   <li>{@code SENSIBLE_TYPED_EVO} - as above plus Follow Evolutions and guaranteed starting moves, so the
 *       inherit-and-repair path and the slot padding are both covered. On Gen 7 this also turns on
 *       evolution-moves-for-all, which is where level-0 slots come from.</li>
 *   <li>{@code SENSIBLE_PLAIN} - Sensible Movesets on, Completely Random: {@code typeStructured} is off, so
 *       every attacking slot is an untyped ATTACK and the STAB machinery is inert. A flat result here is
 *       expected, not a failure.</li>
 *   <li>{@code LEGACY_TYPED} - Sensible Movesets off: the original upstream per-slot picking path, which
 *       {@link SpeciesMovesetRandomizer#randomizeEggMoves()} always uses regardless of config.</li>
 * </ul>
 * The games are picked for the code paths they alone reach: Red for the Gen 1 lack of a physical/special
 * split, Emerald for the first generation with abilities (so {@code abilityAffinity} is live), Platinum as a
 * mid-generation control, and Ultra Sun for evolution moves and cosmetic formes.
 * <p>
 * Named to match the {@code *Randomizer*Test} filter so it runs under the {@code testROMs} Gradle task (which
 * sets {@code romsPath}); it does NOT extend {@link RandomizerTest}, so it loads each ROM itself by explicit
 * file name. A ROM that is not present in {@code roms/} skips its case - check {@code skipped=} against
 * {@code tests=} in the result XML, because an all-skipped suite still reports {@code failures="0"}.
 * <pre>{@code  ./gradlew.bat :random:testROMs --tests "*SpeciesMovesetsGoldenMaster*" }</pre>
 * <b>Runtime:</b> the Ultra Sun cases load a multi-GB 3DS dump four times, so a full run takes several
 * minutes. This is an on-demand characterization test, not the inner dev loop.
 * <p>
 * <b>Re-blessing:</b> after an intentional behaviour change, run with {@code -Dgolden.record=true}. Each case
 * then prints a paste-ready {@code EXPECTED.put(...)} block instead of asserting; copy the blocks into
 * {@link #EXPECTED} and drop the flag. The flag only prints - it does not edit this file, and the recording
 * run passes trivially, so "saw BUILD SUCCESSFUL" is not evidence of a re-bless. Read the blocks out of
 * {@code random/build/test-results/testROMs/TEST-*.xml}, and pass {@code --rerun-tasks} so a repeated
 * recording run is not skipped as up-to-date.
 */
