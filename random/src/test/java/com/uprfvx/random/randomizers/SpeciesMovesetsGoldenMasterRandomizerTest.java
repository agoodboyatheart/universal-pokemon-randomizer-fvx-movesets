    @ParameterizedTest(name = "{1} [{0}]")
    @MethodSource("cases")
    public void speciesMovesetsGoldenMaster(String config, String gameName, String fileBaseName) {
        RomHandler romHandler = loadRom(gameName, fileBaseName);
        String key = gameName + "/" + config;
        String actual = canonicalBlock(romHandler, config);

        if (Boolean.getBoolean("golden.record")) {
            printPasteReadyBlock(key, actual);
            return;
        }
        String expected = EXPECTED.get(key);
        if (expected == null) {
            printPasteReadyBlock(key, actual);
            assumeTrue(false, "No frozen snapshot for " + key
                    + " - run with -Dgolden.record=true and paste the printed block into EXPECTED.");
        }
        assertEquals(expected.strip(), actual.strip(),
                "Species moveset output drifted for " + key + " (seed " + SEED + ")");
    }

    private RomHandler loadRom(String gameName, String fileBaseName) {
        assumeTrue(ROMS_PATH != null, "romsPath not set (run via the testROMs task)");
        Generation gen = Generation.GAME_TO_GENERATION.get(gameName);
        String fullRomName = ROMS_PATH + "/" + fileBaseName + gen.getFileSuffix();
        assumeTrue(new File(fullRomName).exists(), "ROM not present: " + fullRomName);
        RomHandler.Factory factory = gen.createFactory();
        assumeTrue(factory.isLoadable(fullRomName), "ROM not loadable: " + fullRomName);
        RomHandler romHandler = factory.create();
        romHandler.loadRom(fullRomName);
        return romHandler;
    }

    /**
     * The deterministic fingerprint of one (ROM, config) pair: an even spread of species learnsets followed by
     * an even spread of egg-move sets. Both randomizers run against one shared {@link Random}, in the order
     * {@code GameRandomizer} calls them, so the frozen block covers the egg path's RNG position too and not
     * just its content.
     * <p>
     * Read back through {@code getMovesLearnt()} rather than from the in-memory map the randomizer mutated, so
     * what is frozen is what actually lands in the ROM.
     */
    private String canonicalBlock(RomHandler romHandler, String config) {
        romHandler.getRestrictedSpeciesService().setRestrictions(new GenRestrictions());

        Settings s = new Settings();
        applyConfig(s, config, romHandler.generationOfPokemon());
        SpeciesMovesetRandomizer randomizer = new SpeciesMovesetRandomizer(romHandler, s, new Random(SEED));
        randomizer.randomizeMovesLearnt();
        randomizer.randomizeEggMoves();

        StringBuilder sb = new StringBuilder();
        appendLearnsets(sb, romHandler);
        appendEggMoves(sb, romHandler);
        return sb.toString().strip();
    }

    /**
     * Turns a config name into settings. Evolution-moves-for-all is gated to Gen 7 to match the GUI, which
     * only offers it there - the randomizer itself reads the flag unconditionally, so setting it on an older
     * game would freeze a state the application can never actually produce.
     */
    private static void applyConfig(Settings s, String config, int generation) {
        s.setBlockBrokenMovesetMoves(true);
        switch (config) {
            case SENSIBLE_TYPED -> {
                s.setMovesetsMod(Settings.MovesetsMod.RANDOM_PREFER_SAME_TYPE);
                s.setSensibleMovesets(true);
                s.setMovesetsForceGoodDamaging(true);
                s.setMovesetsGoodDamagingPercent(30);
            }
            case SENSIBLE_TYPED_EVO -> {
                s.setMovesetsMod(Settings.MovesetsMod.RANDOM_PREFER_SAME_TYPE);
                s.setSensibleMovesets(true);
                s.setMovesetsFollowEvolutions(true);
                s.setStartWithGuaranteedMoves(true);
                s.setGuaranteedMoveCount(4);
                s.setEvolutionMovesForAll(generation >= 7);
            }
            case SENSIBLE_PLAIN -> {
                s.setMovesetsMod(Settings.MovesetsMod.COMPLETELY_RANDOM);
                s.setSensibleMovesets(true);
            }
            case LEGACY_TYPED -> {
                s.setMovesetsMod(Settings.MovesetsMod.RANDOM_PREFER_SAME_TYPE);
                s.setMovesetsForceGoodDamaging(true);
                s.setMovesetsGoodDamagingPercent(30);
            }
            default -> throw new IllegalArgumentException("Unknown config: " + config);
        }
    }

    /**
     * One line per sampled species: {@code #num TYPES: level:move,level:move,...}. Species are identified by
     * number rather than name deliberately - names carry glyphs (Nidoran) that mangle on the way through the
     * result XML, and the number is what the movesets map is keyed by anyway.
     */
    private static void appendLearnsets(StringBuilder sb, RomHandler romHandler) {
        Map<Integer, List<MoveLearnt>> movesets = romHandler.getMovesLearnt();
        Map<Integer, Species> byNumber = speciesByNumber(romHandler);
        List<Integer> numbers = new ArrayList<>(movesets.keySet());
        for (int idx : evenSpread(numbers.size(), SPECIES_SAMPLE)) {
            int number = numbers.get(idx);
            String moves = orNone(movesets.get(number).stream()
                    .map(ml -> ml.level + ":" + ml.move)
                    .collect(Collectors.joining(",")));
            sb.append(String.format("#%03d ", number)).append(typeStr(byNumber.get(number)))
                    .append(": ").append(moves).append('\n');
        }
    }

    /**
     * One line per sampled species' egg moves. Gen 1 has none at all, which is recorded with an explicit
     * marker so its absence is frozen rather than silently blank.
     */
    private static void appendEggMoves(StringBuilder sb, RomHandler romHandler) {
        Map<Integer, List<Integer>> eggMoves = romHandler.getEggMoves();
        if (eggMoves.isEmpty()) {
            sb.append("# EGG: (none)\n");
            return;
        }
        List<Integer> numbers = new ArrayList<>(eggMoves.keySet());
        for (int idx : evenSpread(numbers.size(), EGG_SAMPLE)) {
            int number = numbers.get(idx);
            String moves = orNone(eggMoves.get(number).stream()
                    .map(String::valueOf).collect(Collectors.joining(",")));
            sb.append(String.format("EGG #%03d: ", number)).append(moves).append('\n');
        }
    }

    /**
     * An empty move list would end its line in a trailing space, and a Java text block strips incidental
     * trailing whitespace from every line - so the frozen snapshot could never match what the ROM produced.
     * An explicit marker keeps "this species has no moves" a value that survives the round trip.
     */
    private static String orNone(String joined) {
        return joined.isEmpty() ? "(none)" : joined;
    }

    /** Species are looked up by the same number the movesets map is keyed by, alt formes included. */
    private static Map<Integer, Species> speciesByNumber(RomHandler romHandler) {
        Map<Integer, Species> byNumber = new LinkedHashMap<>();
        for (Species sp : romHandler.getSpeciesSetInclFormes()) {
            byNumber.putIfAbsent(sp.getNumber(), sp);
        }
        return byNumber;
    }

    /**
     * Indices of an even spread of {@code sample} items across {@code size} (all of them if
     * {@code size <= sample}). Pure integer arithmetic - no RNG - so the choice is deterministic given the
     * ROM's species count.
     */
    private static int[] evenSpread(int size, int sample) {
        if (size <= sample) {
            return IntStream.range(0, size).toArray();
        }
        int[] idx = new int[sample];
        for (int i = 0; i < sample; i++) {
            idx[i] = (int) Math.round((double) i * (size - 1) / (sample - 1));
        }
        return idx;
    }

    /** Prints the paste-ready {@code EXPECTED.put(...)} block for the re-bless workflow (see class doc). */
    private static void printPasteReadyBlock(String key, String actual) {
        System.out.println("\nEXPECTED.put(\"" + key + "\", \"\"\"\n" + actual + "\n\"\"\");");
    }

    private static String typeStr(Species pk) {
        if (pk == null) {
            return "?";
        }
        Type t2 = pk.getSecondaryType(false);
        return pk.getPrimaryType(false) + (t2 == null ? "" : "/" + t2);
    }
